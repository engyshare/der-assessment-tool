@pytest.fixture
def recovery_probe_assumptions(tmp_path: Path) -> Path:
    """**동반 하락에서 회수되는** 대장 사본의 경로.

    실물 대장을 읽어 두 항목의 `sensitivity.low` 만 바꿔 쓴다. 손으로 적은
    사본을 두지 않는 이유는 그것이 대장의 둘째 정본이 되기 때문이다 — 대장이
    바뀌어도 사본은 조용히 옛 값을 들고 있다.

    ⚠ **이름이 R41 에 바뀌었다** (`flip_probe_assumptions` → 지금 이름). 종전
    이름은 *전환* 갈래를 주장했는데 그 갈래는 실물로 옮겨 갔고, 남은 것은 회수
    갈래뿐이다 — 이름이 자기 쓰임보다 넓게 주장하면 다음 사람이 전환을 재는 데
    이것을 쓴다. 이 저장소가 열일곱 번 만난 형태다.
    """
    data = yaml.safe_load(_ASSUMPTIONS.read_text(encoding="utf-8"))
    by_key = {item.get("key"): item for item in data["assumptions"]}
    for key, level, value in _WIDENED:
        item = by_key.get(key)
        # 대장에서 항목이 사라지면 **즉시** 알아야 한다 — 조용히 넘기면 탐침이
        # 실물과 같아지고, 그 순간 이 탐침을 쓰는 검사들이 0회 순회로 통과한다.
        assert item is not None, (
            f"대장에 {key} 가 없다 — 탐침이 넓힐 범위를 찾지 못했다"
        )
        item["sensitivity"][level] = value
    path = tmp_path / "assumptions-recovery-probe.yaml"
    path.write_text(
        yaml.safe_dump(data, allow_unicode=True, sort_keys=False), encoding="utf-8"
    )
    return path
